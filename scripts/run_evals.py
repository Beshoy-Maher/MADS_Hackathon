"""Run the guardrail trick-prompt evals and write evals/results.md.

    python scripts/run_evals.py          # rule layer only: no model, no network, deterministic
    python scripts/run_evals.py --deep   # also the model's second opinion, on prompts the rules have never seen

Two sets, reported separately:
* evals/trick_prompts.json: regression set. The rules were written with these prompts in view, so 100% is expected.
* evals/heldout_prompts.json: written after the rules and never used to tune them. The rule layer alone misses
  most of these by design; --deep measures what the rules plus the model's second opinion refuse.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
import guardrails  # noqa: E402


def regression_rows(d: dict) -> list[tuple]:
    rows = []
    for c in d["requests_blocked"]:
        v = guardrails.screen_request(c["text"])
        rows.append(("refuse", c["text"], c["expect"], v.category or "allowed", (not v.allowed) and v.category == c["expect"]))
    for t in d["requests_allowed"]:
        v = guardrails.screen_request(t)
        rows.append(("allow", t, "allowed", v.category or "allowed", v.allowed))
    for c in d["briefs_blocked"]:
        v = guardrails.screen_brief({"idea": c["idea"]})
        rows.append(("refuse brief", c["idea"], c["expect"], v.category or "allowed", (not v.allowed) and v.category == c["expect"]))
    for c in d.get("briefs_clarify", []):
        v = guardrails.screen_brief({"idea": c["idea"]})
        rows.append(("scope check", c["idea"], c["expect"], v.category or "allowed", v.allowed and v.clarify and v.category == c["expect"]))
    for t in d["briefs_allowed"]:
        v = guardrails.screen_brief({"idea": t})
        rows.append(("allow brief", t, "allowed", v.category or "allowed", v.allowed and not v.clarify))
    return rows


def deep_section(d: dict, held: list[str]) -> tuple[list[str], bool]:
    """Rules plus the model's second opinion. Needs a running model; says so honestly when there is none."""
    import llm
    st = llm.model_status(force=True)
    if not st.get("ready"):
        return ["", "## Held-out prompts (rules + model second opinion)", "",
                f"Not measured: no model was available ({st.get('detail')})."], False
    rule_hits = sum(not guardrails.screen_request(t).allowed for t in held)
    rows, refused = [], 0
    for t in held:
        v = guardrails.screen_request_deep(t)
        refused += not v.allowed
        rows.append(f"| {t.replace('|', '/')} | {v.category or 'allowed'} | {'model' if 'model-judge' in v.matches else ('rules' if not v.allowed else '-')} | {'yes' if not v.allowed else 'NO'} |")
    benign = d["requests_allowed"]
    wrong = [t for t in benign if not guardrails.screen_request_deep(t).allowed]
    md = ["", "## Held-out prompts (rules + model second opinion)", "",
          f"Model: `{st['model']}`. These {len(held)} prompts were written after the rules and never used to tune them.", "",
          f"- Rule layer alone: **{rule_hits}/{len(held)}** refused.",
          f"- Rules + model second opinion: **{refused}/{len(held)}** refused.",
          f"- Normal requests wrongly refused by the model layer: **{len(wrong)}/{len(benign)}**.", "",
          "| Prompt | Category | Caught by | Refused |", "|---|---|---|---|"] + rows
    if wrong:
        md += ["", "Normal requests the model layer refused:"] + [f"- {t}" for t in wrong]
    return md, True


def main() -> int:
    deep = "--deep" in sys.argv
    d = json.loads((ROOT / "evals" / "trick_prompts.json").read_text(encoding="utf-8"))
    held = json.loads((ROOT / "evals" / "heldout_prompts.json").read_text(encoding="utf-8"))["requests_blocked"]
    rows = regression_rows(d)
    total, passed = len(rows), sum(r[4] for r in rows)
    md = [f"# Guardrail eval results: {passed}/{total} passed", "",
          "Generated by `scripts/run_evals.py` from `evals/trick_prompts.json` (rule layer only, no model needed). "
          "This is a regression set: the rules were written with these prompts in view. "
          "How the guardrails do on prompts they have never seen is measured with `--deep` on `evals/heldout_prompts.json`.", "",
          "| Expected | Prompt | Expected category | Got | Pass |", "|---|---|---|---|---|"]
    md += [f"| {a} | {t.replace('|', '/')} | {e} | {g} | {'yes' if ok else 'NO'} |" for a, t, e, g, ok in rows]
    if deep:
        section, _ = deep_section(d, held)
        md += section
    (ROOT / "evals" / "results.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"{passed}/{total} passed (regression set, rule layer)")
    if not deep:
        rule_hits = sum(not guardrails.screen_request(t).allowed for t in held)
        print(f"held-out set, rule layer alone: {rule_hits}/{len(held)} refused. Run with --deep and a model to measure both layers.")
    return 0 if passed == total else 1


if __name__ == "__main__":
    raise SystemExit(main())
