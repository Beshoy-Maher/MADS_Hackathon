"""Runs the trick prompts in evals/trick_prompts.json through the guardrails and writes evals/results.md."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
import guardrails  # noqa: E402


def main():
    cases = json.loads((ROOT / "evals" / "trick_prompts.json").read_text())
    rows, ok = [], 0
    for expect, prompts in (("refuse", cases["must_refuse"]), ("allow", cases["must_allow"])):
        for p in prompts:
            r = guardrails.screen_brief(p)
            got = "allow" if r["allowed"] else "refuse"
            ok += got == expect
            rows.append(f"| {p} | {expect} | {got} | {'PASS' if got == expect else 'FAIL'} | {'; '.join(r['reasons'])} |")
    total = len(rows)
    md = (f"# Guardrail evals\n\nGenerated by `python scripts/run_evals.py`. **{ok}/{total} passed.**\n\n"
          "The rules in guardrails.py are general patterns; these prompts are a test set, not a list the code looks up.\n\n"
          "| Prompt | Expected | Got | Result | Reason |\n|---|---|---|---|---|\n" + "\n".join(rows) + "\n")
    (ROOT / "evals" / "results.md").write_text(md)
    print(f"{ok}/{total} passed")
    return ok == total


if __name__ == "__main__":
    sys.exit(0 if main() else 1)
