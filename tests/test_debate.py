def test_correction_goes_to_the_file_its_objection_quotes(monkeypatch, tmp_path):
    """Phase 3: the builder wrote both the spec and the product; a product quote must be fixed in the product."""
    spec, product = tmp_path / "phase3_step1_spec.md", tmp_path / "phase3_step2_product.md"
    spec.write_text("# Spec\nFour modules for junior analysts.\n", encoding="utf-8")
    product.write_text("# Product\n1. Use SQLite because it is widely used in learning environments.\n", encoding="utf-8")

    def fake(system, user, fallback, *, max_tokens=1200, temperature=None, role="writer"):
        res = llm.LLMResult(text="{}", model=role)
        if role == "critic":
            return {"objections": [{"document": 2, "quote": "because it is widely used in learning environments",
                                    "problem": "Unsupported.", "severity": "medium"}]}, res
        assert "phase3_step2_product.md" in user  # the author sees the document that was quoted
        return {"responses": [{"id": 1, "stance": "concede", "reply": "ok", "fix": "because it runs anywhere without setup"}]}, res
    monkeypatch.setattr(llm, "complete_json", fake)
    docs = [{"file": spec.name, "author": "builder", "text": spec.read_text(), "path": str(spec)},
            {"file": product.name, "author": "builder", "text": product.read_text(), "path": str(product)}]
    d = Critic(_run()).debate(3, docs).data
    assert d["fixed"] == 1
    assert "1. Use SQLite because it runs anywhere without setup." in product.read_text()
    assert spec.read_text() == "# Spec\nFour modules for junior analysts.\n"


