def _fake_models(calls):
    """critic: one real quote, one invented quote; author: defends without a source; critic: says resolved."""
    def fake(system, user, fallback, *, max_tokens=1200, temperature=None, role="writer"):
        calls.append(role)
        res = llm.LLMResult(text="{}", model=f"{role}-model")
        if role == "critic" and '"objections"' in user:
            return {"objections": [
                {"document": 1, "quote": "is worth $2 billion and growing fast", "problem": "No source for the market size.",
                 "severity": "high", "evidence": "https://invented.example/report"},
                {"document": 1, "quote": "words that are not in the document at all", "problem": "Invented.", "severity": "low"},
            ]}, res
        if role == "writer":
            return {"responses": [{"id": 1, "stance": "defend", "reply": "Everyone knows this market is big.", "evidence": ""}]}, res
        return {"verdicts": [{"id": 1, "status": "resolved", "reason": "Fine."}]}, res
    return fake


def test_debate_keeps_only_quoted_objections_and_unsourced_defences_stay_open(monkeypatch, tmp_path):
    calls = []
    monkeypatch.setattr(llm, "complete_json", _fake_models(calls))
    res = Critic(_run()).debate(1, [{"file": "phase1_step3_market.md", "author": "market_analyst", "text": DOC}])
    d = res.data
    assert d["ran"] and d["objections"] == 1  # the invented quote was dropped by code
    o = d["items"][0]
    assert o["status"] == "open" and o["stance"] == "defend"  # "resolved" without a fetched source is not accepted
    assert "no fetched source" in o["verdict"]
    assert "invented.example" not in res.content  # a URL the researcher never fetched is not repeated
    assert calls == ["critic", "writer", "critic"]  # critic and author run on their own roles' models
    assert "critic-model" in res.model and "writer-model" in res.model


def _conceding(fix, quote="Junior analysts ask for practice sets"):
    def fake(system, user, fallback, *, max_tokens=1200, temperature=None, role="writer"):
        res = llm.LLMResult(text="{}", model=role)
        if role == "critic":
            return {"objections": [{"document": 1, "quote": quote, "problem": "Overstated.",
                                    "severity": "medium", "evidence": "https://news.ycombinator.com/item?id=1"}]}, res
        return {"responses": [{"id": 1, "stance": "concede", "reply": "Fair.", "fix": fix}]}, res
    return fake


def _doc_file(tmp_path, text=None):
    path = tmp_path / "phase1_step3_market.md"
    path.write_text(text or (DOC + "\n\n---\nGenerated by the pipeline. Model: m. Cost: $0.00.\n"), encoding="utf-8")
    return path


def _log_entries(action):
    p = config.DECISION_LOG_PATH
    return [e for e in json.loads(p.read_text())] if p.exists() and action is None else \
        [e for e in (json.loads(p.read_text()) if p.exists() else []) if e["action"] == action]


def test_conceded_correction_is_written_into_the_document_and_logged(monkeypatch, tmp_path):
    monkeypatch.setattr(llm, "complete_json", _conceding("Some junior analysts ask for practice sets"))
    path = _doc_file(tmp_path)
    before = len(_log_entries("apply_debate_correction"))
    res = Critic(_run()).debate(1, [{"file": path.name, "author": "market_analyst", "text": DOC, "path": str(path)}])
    d = res.data
    assert d["fixed"] == 1 and d["not_applied"] == 0 and d["open"] == 0 and d["items"][0]["status"] == "fixed"
    text = path.read_text()
    assert "Some junior analysts ask for practice sets on Hacker News every week." in text and "Generated by the pipeline" in text
    entries = _log_entries("apply_debate_correction")
    assert len(entries) == before + 1
    e = entries[-1]
    assert e["agent"] == "market_analyst" and e["approved_by"] is None
    assert all(k in e for k in ("action", "sources", "model", "cost", "approved_by"))
    assert "RESOLVED" not in res.content and "1 fixed" in res.content


